import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { writeFileSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import machine, { millingComponents, millingLayout } from '../src/parts/cnc-milling-machine/part';
import { millingLibraries } from '../src/parts/cnc-milling-machine/lib/composition';
import { componentPython } from '../src/core/assembly/detail-instances';
import { withGeometryMode } from '../src/core/geometry-mode';

test(
  'actual portal foot flags and backed X scale clear their installed partners at middle and all eight travel corners in both modes',
  { skip: !process.env.FREECAD_PYTHON, timeout: 620_000 },
  () => {
    const hostIds = new Set([
      'fixed-bed-side-1',
      'gantry-foot-1',
      'gantry-drive-link-1',
      'gantry-box-beam',
      'x-nut-bracket',
      'x-ball-nut',
      'x-saddle-rear',
      'x-saddle-bridge-1',
      'x-saddle-bridge--1',
      'x-z-fixed-saddle',
    ]);
    const isNew = (id: string) => /^[xy]-linear-/.test(id) || /^y-limit-/.test(id);
    const pieces = millingComponents(machine.defaults).filter(
      (piece) =>
        isNew(piece.component.id) ||
        hostIds.has(piece.component.id) ||
        piece.component.parameters.role === 'portal-post',
    );
    const v = millingLayout(machine.defaults);
    const cases = (['simple', 'full'] as const).map((mode) => {
      // Full checks actual threaded mounts. The opaque drive internals are covered
      // by the whole-machine audit, not regenerated by this mounting fixture.
      const selected =
        mode === 'full' ? pieces.filter((piece) => piece.component.id !== 'x-ball-nut') : pieces;
      return {
        mode,
        source: withGeometryMode(mode, () => componentPython(millingLibraries, selected)),
        rows: selected.map((piece) => ({
          id: piece.component.id,
          motion: piece.motion,
          new: isNew(piece.component.id),
        })),
      };
    });
    const executable = process.env.FREECAD_PYTHON!;
    const nativeModule = resolve(dirname(executable), '../lib/FreeCAD.so');
    const runtime = [executable, nativeModule].filter(existsSync).map((path) => {
      const stat = statSync(path);
      return { path, size: stat.size, modified: stat.mtimeMs };
    });
    const runtimeSignature = JSON.stringify(runtime);
    const templates = resolve(
      'test-results/cnc-milling/templates',
      createHash('sha256').update(runtimeSignature).digest('hex'),
    );
    const script = `import FreeCAD as App, Part, math, json, hashlib, os, time
cases=json.loads(${JSON.stringify(JSON.stringify(cases))})
templates=${JSON.stringify(templates)}
proof=[]
for case in cases:
    rows=case['rows'];reused=[]
    scope={'App':App,'Part':Part,'math':math,'os':os,'hashlib':hashlib,'json':json,'templates':templates,'reused':reused}
    persistence="""
_original_component_builder=_pl_component
def _pl_component(source):
    key=hashlib.sha256(source.encode()).hexdigest()
    base=os.path.join(templates,key)
    if source not in _pl_component_cache and os.path.exists(base+'.json') and os.path.exists(base+'.brep'):
        record=json.load(open(base+'.json'))
        with open(base+'.brep','rb') as handle: file_hash=hashlib.sha256(handle.read()).hexdigest()
        if record.get('sourceHash')==key and record.get('fileHash')==file_hash:
            cached=Part.Shape();cached.read(base+'.brep')
            _pl_component_cache[source]=(cached,record['metadata'],record['labels'])
            reused.append({'sourceSha256':key,'fileSha256':file_hash,'path':base+'.brep'})
    return _original_component_builder(source)
"""
    marker='\\ncomponents = []\\ncomponent_metadata = []\\n'
    assert case['source'].count(marker)==1,'Exact native constructor cache marker changed'
    executed=case['source'].replace(marker,'\\n'+persistence+marker)
    print('PORTAL_MOUNT_GENERATION:'+case['mode'],flush=True)
    exec(compile(executed,'actual-portal-encoder-limit-installation','exec'),scope)
    print('PORTAL_MOUNT_GENERATED:'+case['mode'],flush=True)
    components=scope['components']
    assert len(components)==len(rows)
    for row,shape in zip(rows,components):
        assert not shape.isNull() and shape.isValid() and shape.isClosed() and shape.Solids and math.isfinite(shape.Volume) and shape.Volume>0,row
    byid={row['id']:shape for row,shape in zip(rows,components)}
    witnesses=[]
    for end,sign in [('min',-1),('max',1)]:
        flag=byid['y-limit-'+end+'-target'];foot=byid['gantry-foot-1']
        assert flag.distToShape(foot)[0]<1e-6
        for dy in [-7,7]:
            for dz in [-8,8]:
                point=App.Vector(${v.footPlateCenterX + v.footPlateWidth / 2},sign*${v.footPlateDepth / 2 - 15}+dy,${v.gantryFootBottom + 15}+dz)
                assert foot.isInside(point+App.Vector(-0.2,0,0),1e-7,False),('Foot stock missing at flag',end,point)
                assert flag.isInside(point+App.Vector(0.2,0,0),1e-7,False),('Flag stock missing at foot',end,point)
                witnesses.append({'joint':end+' foot flag','point':list(point)})
    spar=byid['x-linear-spar'];plate=byid['x-linear-backing-plate'];beam=byid['gantry-box-beam']
    for x in [-450,-225,0,225,450]:
        for z in [${v.beamCenter + 48},${v.beamCenter + 75}]:
            point=App.Vector(x,-${v.beamDepth / 2 + 12},z)
            assert plate.isInside(point+App.Vector(0,0.2,0),1e-7,False),('Spar backing stock missing',point)
            assert spar.isInside(point+App.Vector(0,-0.2,0),1e-7,False),('Spar rear wall missing',point)
            witnesses.append({'joint':'X spar continuous backing support','point':list(point)})
    for x in [-440,-225,0,225,440]:
        for z in [${v.beamCenter + 45},${v.beamCenter + 60}]:
            point=App.Vector(x,-${v.beamDepth / 2},z)
            assert beam.isInside(point+App.Vector(0,0.2,0),1e-7,False),('Lower backing band has no real beam support',point)
            assert plate.isInside(point+App.Vector(0,-0.2,0),1e-7,False),('Backing plate bearing strip missing',point)
            witnesses.append({'joint':'X backing lower beam support','point':list(point)})
    overlaps=[];pairs=0
    poses=[(0,0,0)]+[(x,y,z) for x in [-400,400] for y in [-750,750] for z in [-100,100]]
    for pose in poses:
        placed=[]
        for row,shape in zip(rows,components):
            value=shape.copy()
            value.translate(App.Vector(pose[0] if row['motion'] in ['x','z'] else 0,pose[1] if row['motion']!='fixed' else 0,pose[2] if row['motion']=='z' else 0))
            placed.append(value)
        for i,a in enumerate(placed):
            for j in range(i+1,len(placed)):
                if not(rows[i]['new'] or rows[j]['new']):continue
                b=placed[j];ab=a.BoundBox;bb=b.BoundBox
                if min(ab.XMax,bb.XMax)-max(ab.XMin,bb.XMin)<1e-7 or min(ab.YMax,bb.YMax)-max(ab.YMin,bb.YMin)<1e-7 or min(ab.ZMax,bb.ZMax)-max(ab.ZMin,bb.ZMin)<1e-7:continue
                common=a.common(b);volume=common.Volume
                assert math.isfinite(volume),(rows[i],rows[j],pose)
                if common.Solids:assert common.isValid() and common.isClosed(),(rows[i],rows[j],pose)
                if abs(volume)>0.001:overlaps.append({'a':rows[i]['id'],'b':rows[j]['id'],'pose':pose,'volumeMm3':volume})
                pairs+=1
    record={'mode':case['mode'],'geometrySourceSha256':hashlib.sha256(case['source'].encode()).hexdigest(),'components':len(rows),'poses':poses,'nativePairs':pairs,'positiveContactWitnesses':witnesses,'overlaps':overlaps,'reusedExactTemplates':reused,'scope':'Actual source encoder/limit units and their mounting hosts. Simple additionally checks the unchanged purchased X ball-nut exterior; Full drive internals belong to the whole-machine audit.'}
    proof.append(record)
    open('/tmp/protolab-cnc-portal-sensors-native.json','w').write(json.dumps(proof,indent=2))
    assert not overlaps,overlaps
print('PORTAL_SENSOR_NATIVE_PASSED')
`;
    const path = '/tmp/protolab-cnc-portal-sensors-native.py';
    writeFileSync(path, script);
    const result = spawnSync(process.env.FREECAD_PYTHON!, [path], {
      encoding: 'utf8',
      timeout: 610_000,
      maxBuffer: 2_000_000,
    });
    assert.equal(result.status, 0, result.stdout + result.stderr);
    assert.ok(result.stdout.includes('PORTAL_SENSOR_NATIVE_PASSED'));
  },
);

export function translateSearchQuery(query: string): string {
  const tokens = query.match(words) ?? [];
  if (!tokens.some((token) => searchTerms.has(token.toLowerCase()))) return query;
  const translated = new Set<string>();
  return query
    .replace(words, (token) => {
      const key = token.toLowerCase();
      const term = searchTerms.get(key);
      if (term) {
        if (translated.has(term)) return '';
        translated.add(term);
        return term;
      }
      return linkingWords.has(key) ? '' : token;
    })
    .replace(/\s+/g, ' ')
    .trim();
}

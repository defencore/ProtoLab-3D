export function layout(p: Parameters, state = 'assembled') {
  const angle = Number(p.outputAngle ?? 0),
    radians = (angle * Math.PI) / 180;
  const displacement = -fixed.lever * Math.tan(radians);
  const screwTurns = -displacement / thread.lead;
  return {
    ...fixed,
    thread,
    angle,
    radians,
    displacement,
    nutX: fixed.outputX + displacement,
    screwTurns,
    motorTurns: -screwTurns,
    screwAngle: 360 * screwTurns,
    motorAngle: -360 * screwTurns,
    pinRadius: fixed.lever / Math.cos(radians),
    inspection: state === 'drive' || state === 'output',
  };
}

export function millingPose(p: Parameters, state: string) {
  const q = { ...p };
  if (state === 'x-min') q.xPosition = 0;
  if (state === 'x-max') q.xPosition = 100;
  if (state === 'y-min') q.yPosition = 0;
  if (state === 'y-max') q.yPosition = 100;
  if (state === 'z-min') q.zPosition = 0;
  if (state === 'z-max') q.zPosition = 100;
  return millingLayout(q);
}
